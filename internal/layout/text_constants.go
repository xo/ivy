import "strings"

// langQuote is an entry of LANG_QUOTES: a language and its open and close
// quotes, from the outer level to the inner levels.
type langQuote struct {
	lang   string
	quotes [2][]string
}

// getLangQuotes is get_lang_quotes in weasyprint/text/constants.py. It
// returns the open and the close quotes of a language.
func getLangQuotes(lang string) [2][]string {
	for _, entry := range langQuotes {
		if entry.lang != "" && entry.lang == lang {
			return entry.quotes
		}
	}
	// Revert to find long names before short ones
	for i := len(langQuotes) - 1; i >= 0; i-- {
		if key := langQuotes[i].lang; key != "" && strings.HasPrefix(lang, key) {
			return langQuotes[i].quotes
		}
	}
	return langQuotes[0].quotes
}

